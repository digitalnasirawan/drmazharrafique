export const getRouteByPath = (path: string): RouteItem | undefined => {
  const normalized = path === '/' ? '/' : path.endsWith('/') ? path : `${path}/`;
  return routesRegistry.find(r => r.canonicalPath === normalized);
};

export const getRouteById = (id: string): RouteItem | undefined => {
  return routesRegistry.find(r => r.pageId === id);
};

export const getChildRoutes = (parentId: string): RouteItem[] => {
  return routesRegistry.filter(r => r.parentPageId === parentId);
};
